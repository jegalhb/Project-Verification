def to_major(purpose_code):
    """
    용도코드 → 별표1 대분류명.

    >>> to_major("04001")
    '제2종근린생활시설'
    >>> to_major("03002")
    '제1종근린생활시설'
    >>> to_major("Z3999") is None
    True
    """
    if not purpose_code:
        return None
    code = str(purpose_code).strip()
    if code in EXCEPTIONS:
        return EXCEPTIONS[code]
    return BYLPYO1.get(code[:2])


