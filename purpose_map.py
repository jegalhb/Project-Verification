    code = str(purpose_code or "").strip()
    if code in SEPTIC_COEF:
        return SEPTIC_COEF[code], "확정"
    if code[:2] in HOUSING_PREFIX:
        return None, "산정불가"       # 주택류는 거실 수 기반
