def facility_group(purpose_code):
    """용도코드 → 시설군 번호. 다중생활시설 예외 반영."""
    if str(purpose_code) in MULTI_LIVING:
        return 5
    return FACILITY_GROUP.get(to_major(purpose_code))


def restaurant_verdict(purpose_code, target="일반음식점"):
    """
    해당 층에서 목표 업종 영업이 가능한지 판정.

    「건축법」 제19조 — 용도변경은 시설군 이동 방향으로 결정됩니다.
      상위군(번호가 작은 군)으로 변경  → 허가
      하위군(번호가 큰 군)으로 변경    → 신고
      같은 군 안에서의 변경            → 건축물대장 기재내용 변경 신청

    반환: (판정, 사유)
      '현 용도 그대로'  이미 목표 업종의 용도코드
      '기재내용 변경'   같은 시설군 안 — 가장 가벼움
      '용도변경 신고'   하위군으로 이동
      '용도변경 허가'   상위군으로 이동 — 가장 무거움
      '확인 필요'      코드 미매핑
    """
    code = str(purpose_code or "").strip()
    major = to_major(code)
    if major is None:
        return "확인 필요", f"용도코드 미매핑({code}) — 관할 구청 확인"

    want_code, want_major = TARGET_USE.get(target, TARGET_USE["일반음식점"])
    if code == want_code:
        return "현 용도 그대로", f"이미 {target}"

    src = facility_group(code)
    dst = FACILITY_GROUP.get(want_major)
    if src is None or dst is None:
        return "확인 필요", f"{major} — 시설군 판별 불가"

    if src == dst:
        return "기재내용 변경", f"{major} → {target} · 같은 {GROUP_NAME[src]}"
    if dst < src:
        # 목표 시설군 번호가 더 작음 = 상위군으로 이동 → 허가
        return "용도변경 허가", (f"{major}({GROUP_NAME[src]}) → "
                            f"{want_major}({GROUP_NAME[dst]}) · 상위군 이동")
    # 목표 시설군 번호가 더 큼 = 하위군으로 이동 → 신고
    return "용도변경 신고", (f"{major}({GROUP_NAME[src]}) → "
                        f"{want_major}({GROUP_NAME[dst]}) · 하위군 이동")


def describe(purpose_code, purpose_name="", target="일반음식점"):
    """판정 결과를 한 줄로 설명."""
    major = to_major(purpose_code)
    verdict, reason = restaurant_verdict(purpose_code, target)
    return (f"{purpose_name or '?'}({purpose_code}) · {major or '?'}"
            f"  →  {verdict}   [{reason}]")


